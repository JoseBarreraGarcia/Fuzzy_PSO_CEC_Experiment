"""
Simple Paper Analysis - Generates figures and tables for conference paper
No special characters, handles w_timeseries CSV format from analisis.py

Output:
- Resultados/paper_outputs/paper_fig_diversity_timeline.pdf
- Resultados/paper_outputs/paper_table_diversity_stats.tex  
- Resultados/paper_outputs/paper_fig_rule_heatmap.pdf
"""

import pandas as pd
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
import warnings
warnings.filterwarnings('ignore')

# LNCS Configuration
plt.rcParams['font.family'] = 'Times New Roman'
plt.rcParams['font.size'] = 10
plt.rcParams['figure.dpi'] = 300

TRANSITORIO_PATH = Path("Resultados/transitorio")
OUTPUT_PATH = Path("Resultados/paper_outputs")
OUTPUT_PATH.mkdir(exist_ok=True, parents=True)

def load_timeseries_data():
    """Load w_timeseries CSVs generated by analisis.py"""
    files = list(TRANSITORIO_PATH.glob("w_timeseries*.csv"))
    
    if not files:
        print("[ERROR] No w_timeseries files found in Resultados/transitorio/")
        return None
    
    print("[OK] Found " + str(len(files)) + " w_timeseries files")
    
    all_data = []
    for f in files:
        try:
            df = pd.read_csv(f)
            # Extract instance from filename: w_timeseries_SCP_41_S4-ELIT.csv
            parts = f.stem.split('_')
            instance = 'SCP' + parts[2]  
            df['instance'] = instance
            all_data.append(df)
        except Exception as e:
            print("[WARN] Error loading " + f.name + ": " + str(e))
    
    if not all_data:
        return None
    
    return pd.concat(all_data, ignore_index=True)


def classify_phase(iteration, max_iter=500):
    """Classify iteration into early/mid/late phase"""
    progress = iteration / max_iter
    if progress < 0.3:
        return 'Early'
    elif progress < 0.7:
        return 'Mid'
    else:
        return 'Late'


def generate_diversity_timeline(df):
    """Generate Figure: Diversity evolution over iterations"""
    
    if df is None or df.empty:
        print("[ERROR] No data to plot")
        return
    
    print("[PLOTTING] Generating diversity timeline...")
    
    fig, axes = plt.subplots(2, 3, figsize=(10, 6), sharex=True, sharey=True)
    axes = axes.flatten()
    
    mh_types = ['PSO', 'PSO_FCS:A', 'PSO_FCS:B', 'PSO_FCS:C', 'PSO_FCS:D']
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728', '#9467bd']
    
    for idx, mh_type in enumerate(mh_types):
        ax = axes[idx]
        data = df[df['MH'] == mh_type]
        
        if data.empty:
            continue
        
        # Plot mean diversity with bands
        grouped = data.groupby('iter')['div'].agg(['mean', 'std']).reset_index()
        ax.plot(grouped['iter'], grouped['mean'], color=colors[idx], linewidth=2, label=mh_type)
        ax.fill_between(grouped['iter'], 
                       grouped['mean'] - grouped['std'],
                       grouped['mean'] + grouped['std'],
                       color=colors[idx], alpha=0.2)
        
        # Phase dividers
        ax.axvline(150, color='gray', linestyle='--', alpha=0.5, linewidth=0.8)
        ax.axvline(350, color='gray', linestyle='--', alpha=0.5, linewidth=0.8)
        
        ax.set_title(mh_type, fontsize=10, fontweight='bold')
        ax.set_ylabel('Diversity', fontsize=9)
        ax.grid(True, alpha=0.3)
        ax.set_ylim(0, 1)
    
    # Hide the empty 6th subplot
    axes[5].axis('off')
    
    for ax in axes[3:5]:
        ax.set_xlabel('Iteration', fontsize=9)
    
    plt.tight_layout()
    output_file = OUTPUT_PATH / "paper_fig_diversity_timeline.pdf"
    plt.savefig(output_file, bbox_inches='tight', dpi=300)
    print("[OK] Saved: " + str(output_file))
    plt.close()


def generate_rule_heatmap(df):
    """Generate Figure: Rule activation frequency (simplified)"""
    
    if df is None or df.empty:
        print("[ERROR] No data for heatmap")
        return
    
    print("[PLOTTING] Generating rule heatmap...")
    
    # Simplified: create a 3x3 matrix showing w_value by diversity/progress bins
    df['div_bin'] = pd.cut(df['div'], bins=[0, 0.4, 0.7, 1.0], labels=['low', 'medium', 'high'])
    df['prog_bin'] = pd.cut(df['progress'], bins=[0, 0.4, 0.7, 1.0], labels=['early', 'mid', 'late'])
    
    # Average w value per bin
    pivot = df.pivot_table(values='w', index='div_bin', columns='prog_bin', aggfunc='mean')
    
    fig, ax = plt.subplots(figsize=(6, 4.5))
    sns.heatmap(pivot, annot=True, fmt='.2f', cmap='YlOrRd', ax=ax, cbar_kws={'label': 'Mean w'})
    ax.set_xlabel('Iteration Progress', fontsize=10, fontweight='bold')
    ax.set_ylabel('Diversity', fontsize=10, fontweight='bold')
    ax.set_title('Inertia Weight by Input Region', fontsize=11, fontweight='bold')
    
    plt.tight_layout()
    output_file = OUTPUT_PATH / "paper_fig_rule_heatmap.pdf"
    plt.savefig(output_file, bbox_inches='tight', dpi=300)
    print("[OK] Saved: " + str(output_file))
    plt.close()


def generate_latex_tables(df):
    """Generate LaTeX tables for diversity statistics"""
    
    if df is None or df.empty:
        print("[ERROR] No data for tables")
        return
    
    print("[GENERATING] LaTeX tables...")
    
    # Diversity statistics by phase
    df['phase'] = df['iter'].apply(classify_phase)
    
    stats = df.groupby('phase')['div'].agg([
        ('Mean', 'mean'),
        ('Std', 'std'),
        ('Min', 'min'),
        ('Max', 'max')
    ]).round(3)
    
    latex_table = r"""\begin{table}[t]
\centering
\caption{Diversity statistics by search phase}
\label{tab:diversity_stats}
\begin{tabular}{lcccc}
\hline
\textbf{Phase} & \textbf{Mean} & \textbf{Std} & \textbf{Min} & \textbf{Max} \\
\hline
"""
    
    for phase in ['Early', 'Mid', 'Late']:
        if phase in stats.index:
            row = stats.loc[phase]
            latex_table += f"{phase} & {row['Mean']:.3f} & {row['Std']:.3f} & {row['Min']:.3f} & {row['Max']:.3f} \\\\\n"
    
    latex_table += r"""\hline
\end{tabular}
\end{table}
"""
    
    output_file = OUTPUT_PATH / "paper_table_diversity_stats.tex"
    with open(output_file, 'w') as f:
        f.write(latex_table)
    print("[OK] Saved: " + str(output_file))


def main():
    print("=" * 60)
    print("PAPER ANALYSIS - SIMPLE VERSION")
    print("=" * 60)
    
    # Load data
    print("[1/4] Loading data...")
    df = load_timeseries_data()
    
    if df is None or df.empty:
        print("[ERROR] No data loaded")
        return
    
    print("[OK] Loaded " + str(len(df)) + " rows")
    print("[OK] MH types: " + str(df['MH'].unique().tolist()))
    
    # Generate figures
    print("[2/4] Generating figures...")
    generate_diversity_timeline(df)
    generate_rule_heatmap(df)
    
    # Generate tables
    print("[3/4] Generating tables...")
    generate_latex_tables(df)
    
    # Save raw data
    print("[4/4] Saving raw data...")
    output_csv = OUTPUT_PATH / "paper_data_raw.csv"
    df.to_csv(output_csv, index=False)
    print("[OK] Saved: " + str(output_csv))
    
    print("\n" + "=" * 60)
    print("ANALYSIS COMPLETE")
    print("=" * 60)
    print("[OK] Outputs in: " + str(OUTPUT_PATH.absolute()))
    print("[OK] Files:")
    for f in OUTPUT_PATH.glob("paper_*"):
        print("    - " + f.name)


if __name__ == "__main__":
    main()
