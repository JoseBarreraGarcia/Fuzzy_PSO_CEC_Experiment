#!/usr/bin/env python
"""
08_export_results_to_manuscript.py — copy figures and tables into the manuscript tree.

Consumes results/figures_all/ and results/tables_all/, drops the assets under
manuscript/figures/ and manuscript/tables/ so that .tex files can \\include /
\\includegraphics them via relative paths, and emits a helper snippet
manuscript/generated/inputs.tex with an example include block.

The script overwrites destination files unconditionally so running the analysis
pipeline again refreshes the manuscript inputs.
"""
from __future__ import annotations

import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
RESULTS = REPO_ROOT / "FUZZY" / "ARTICULO_MDPI" / "results"
MANUSCRIPT = REPO_ROOT / "FUZZY" / "ARTICULO_MDPI" / "manuscript"

FIG_SRC = RESULTS / "figures_all"
TAB_SRC = RESULTS / "tables_all"
FIG_DST = MANUSCRIPT / "figures"
TAB_DST = MANUSCRIPT / "tables"
GEN_DST = MANUSCRIPT / "generated"


def _copy_all(src: Path, dst: Path, patterns: tuple[str, ...]) -> list[Path]:
    dst.mkdir(parents=True, exist_ok=True)
    copied: list[Path] = []
    for pat in patterns:
        for p in src.glob(pat):
            target = dst / p.name
            shutil.copy2(p, target)
            copied.append(target)
    return copied


def _write_inputs_snippet(figures: list[Path], tables: list[Path]) -> None:
    GEN_DST.mkdir(parents=True, exist_ok=True)
    lines = ["% Auto-generated by 08_export_results_to_manuscript.py.",
             "% Include from main.tex with: \\input{generated/inputs.tex}",
             ""]
    lines.append("% ==== FIGURES ====")
    for p in sorted(figures):
        if p.suffix.lower() != ".pdf":
            continue
        stem = p.stem
        rel = f"figures/{p.name}"
        lines.append(f"% Figure asset: {rel} (caption and label are defined at its use site).")
    lines.append("")
    lines.append("% ==== TABLES ====")
    for p in sorted(tables):
        if p.suffix.lower() != ".tex":
            continue
        lines.append(f"% \\input{{tables/{p.name}}}")
    lines.append("")
    (GEN_DST / "inputs.tex").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    print(f"[08] repo root  : {REPO_ROOT}")
    print(f"[08] fig src -> dst : {FIG_SRC} -> {FIG_DST}")
    print(f"[08] tab src -> dst : {TAB_SRC} -> {TAB_DST}")

    figs = _copy_all(FIG_SRC, FIG_DST, ("*.png", "*.pdf"))
    print(f"[08] copied {len(figs)} figure files")
    tabs = _copy_all(TAB_SRC, TAB_DST, ("*.tex",))
    print(f"[08] copied {len(tabs)} table files")

    _write_inputs_snippet(figs, tabs)
    print(f"[08] wrote {GEN_DST / 'inputs.tex'}")

    print("[08] === DONE ===")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
