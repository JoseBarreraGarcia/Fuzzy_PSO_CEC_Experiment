#!/usr/bin/env python
"""
11_generate_function_level_analysis.py — Section 5.2 (function-level performance).

Answers, per benchmark function and per instance, which configuration wins, by how
much, and whether the difference against the classical PSO baseline is significant.
Aggregated rankings alone cannot support the claim that no configuration is
universally dominant; this is the disaggregated evidence for it.

Inputs (all already generated by scripts 02 and 10):
    results/level3_rankings/ranking_per_instance.csv
    results/tests/h4_wilcoxon_vs_baseline/wilcoxon_pairs.csv

Outputs:
    results/level3_rankings/function_level_per_instance.{parquet,csv}
    results/level3_rankings/function_level_per_function.{parquet,csv}
    manuscript/tables/tab_function_level.tex          (body: one row per function)
    manuscript/tables/tab_function_level_full.tex     (supplementary: one row per instance)
    manuscript/figures/fig_function_heatmap.{pdf,png}
    results/figures_all/fig_function_heatmap.{pdf,png}

Naming follows decision D17: a configuration is reported as FCS-<n>-R<k>.
"""
from __future__ import annotations

import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.colors import BoundaryNorm

REPO_ROOT = Path(__file__).resolve().parents[3]
MDPI = REPO_ROOT / "FUZZY" / "ARTICULO_MDPI"
RANKING = MDPI / "results" / "level3_rankings" / "ranking_per_instance.csv"
WILCOXON = MDPI / "results" / "tests" / "h4_wilcoxon_vs_baseline" / "wilcoxon_pairs.csv"
META = MDPI / "results" / "level1_raw" / "experiments_meta.parquet"
OUT_L3 = MDPI / "results" / "level3_rankings"
OUT_FIG = MDPI / "results" / "figures_all"
MS_TABLES = MDPI / "manuscript" / "tables"
MS_FIGURES = MDPI / "manuscript" / "figures"

ALPHA = 0.05

# Landscape classes follow the benchmark definition used in the experimental design.
# S1/S2 are the scalable vs fixed-dimensional split used for the Pareto analysis and
# are deliberately NOT described as unimodal vs multimodal.
CLASS_UNIMODAL = [f"F{i}" for i in range(1, 8)]        # F1-F7
CLASS_MULTIMODAL = [f"F{i}" for i in range(8, 14)]     # F8-F13
CLASS_FIXED = [f"F{i}" for i in range(14, 24)]         # F14-F23


def landscape_class(function: str) -> str:
    if function in CLASS_UNIMODAL:
        return "Unimodal"
    if function in CLASS_MULTIMODAL:
        return "Multimodal (scalable)"
    return "Fixed-dimensional"


def subset(function: str) -> str:
    return "S2" if function in CLASS_FIXED else "S1"


def short_name(mh_raw: str) -> str:
    """PSO_FCS:G3:I1:R1:O1 -> FCS-3-R1 (D17). PSO stays PSO."""
    if mh_raw == "PSO":
        return "PSO"
    m = re.search(r"G(\d+).*?:(R\d+)", mh_raw)
    return f"FCS-{m.group(1)}-{m.group(2)}" if m else mh_raw


def function_order(functions: pd.Series) -> list[str]:
    return sorted(functions.unique(), key=lambda f: int(f[1:]))


def build_per_instance(rank: pd.DataFrame, wil: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for instance, block in rank.groupby("instance", sort=False):
        pso = block[block["mh_raw"] == "PSO"].iloc[0]
        fcs = block[block["mh_family"] == "PSO_FCS"]
        # Deterministic tie-break: lowest rank, then coarsest granularity, then rule order.
        best = fcs.sort_values(["rank", "n_labels", "rule_set"]).iloc[0]
        tied = int((fcs["rank"] == best["rank"]).sum())

        test = wil[(wil["instance"] == instance) & (wil["mh_raw"] == best["mh_raw"])]
        p_value = float(test["p_value"].iloc[0]) if len(test) else np.nan
        a12 = float(test["a12"].iloc[0]) if len(test) else np.nan
        direction = test["direction_alpha_0.05"].iloc[0] if len(test) else "n/a"

        gap_pso = float(pso["gap_median"])
        gap_fcs = float(best["gap_median"])
        # Relative improvement is undefined when the baseline already reaches the optimum.
        improvement = (gap_pso - gap_fcs) / gap_pso * 100.0 if gap_pso > 0 else np.nan

        rows.append({
            "instance": instance,
            "function": best["function"],
            "dim": int(best["dim"]),
            "landscape_class": landscape_class(best["function"]),
            "subset": subset(best["function"]),
            "best_fcs_raw": best["mh_raw"],
            "best_fcs": short_name(best["mh_raw"]),
            "best_n": int(best["n_labels"]),
            "best_rule": best["rule_set"],
            "n_tied_at_best": tied,
            "rank_pso": int(pso["rank"]),
            "rank_best_fcs": int(best["rank"]),
            "gap_pso": gap_pso,
            "gap_best_fcs": gap_fcs,
            "improvement_pct": improvement,
            "p_value": p_value,
            "a12": a12,
            "direction": direction,
            # All configurations tie at rank 1 on median normalized gap.
            "fully_tied": bool(tied == len(fcs) and int(pso["rank"]) == 1 and int(best["rank"]) == 1),
            "winner_family": "PSO_FCS" if best["rank"] < pso["rank"] else
                             ("PSO" if pso["rank"] < best["rank"] else "tie"),
        })
    out = pd.DataFrame(rows)
    order = {f: i for i, f in enumerate(function_order(out["function"]))}
    return out.sort_values(["function", "dim"], key=lambda s: s.map(order) if s.name == "function" else s)


def build_per_function(per_instance: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for function, block in per_instance.groupby("function", sort=False):
        all_tied = bool(block["fully_tied"].all())
        counts = block["best_fcs"].value_counts()
        top = counts.index[0]
        if (counts == counts.iloc[0]).sum() > 1:
            # Several configs win the same number of instances: prefer the best mean rank.
            candidates = counts[counts == counts.iloc[0]].index
            means = {c: block.loc[block["best_fcs"] == c, "rank_best_fcs"].mean() for c in candidates}
            top = min(means, key=means.get)
        sel = block[block["best_fcs"] == top]
        sig_wins = int(((block["winner_family"] == "PSO_FCS") & (block["p_value"] < ALPHA)).sum())
        rows.append({
            "function": function,
            "landscape_class": block["landscape_class"].iloc[0],
            "subset": block["subset"].iloc[0],
            "n_instances": len(block),
            "dims": ", ".join(str(d) for d in sorted(block["dim"].unique())),
            "all_tied": all_tied,
            "best_fcs": "--" if all_tied else top,
            "best_n": "--" if all_tied else int(sel["best_n"].iloc[0]),
            "best_rule": "--" if all_tied else sel["best_rule"].iloc[0],
            "rank_pso_median": float(block["rank_pso"].median()),
            "rank_best_fcs_median": float(block["rank_best_fcs"].median()),
            "fcs_wins": int((block["winner_family"] == "PSO_FCS").sum()),
            "significant_wins": sig_wins,
            "a12_median": float(block["a12"].median()),
        })
    return pd.DataFrame(rows)


def add_runtime_overhead(per_function: pd.DataFrame) -> pd.DataFrame:
    """Add median paired FCS-vs-PSO wall-time overhead for each function winner."""
    meta = pd.read_parquet(META)
    baseline = meta.loc[
        meta["mh_family"].eq("PSO"),
        ["exp_name", "function", "dim", "run_id", "t_exec"],
    ].rename(columns={"t_exec": "t_pso"})
    fuzzy = meta.loc[
        meta["mh_family"].eq("PSO_FCS"),
        ["exp_name", "function", "dim", "run_id", "n_labels", "rule_set", "t_exec"],
    ].rename(columns={"t_exec": "t_fcs"})
    paired = fuzzy.merge(
        baseline,
        on=["exp_name", "function", "dim", "run_id"],
        how="left",
        validate="many_to_one",
    )
    if paired["t_pso"].isna().any() or (paired[["t_pso", "t_fcs"]] <= 0).any().any():
        raise ValueError("Runtime overhead requires positive paired FCS and PSO times")
    paired["n_labels"] = paired["n_labels"].astype(int)
    paired["overhead_pct"] = 100.0 * (paired["t_fcs"] / paired["t_pso"] - 1.0)

    overheads = []
    for row in per_function.itertuples(index=False):
        if row.all_tied or row.best_fcs == "--":
            overheads.append(float("nan"))
            continue
        selected = paired.loc[
            paired["function"].eq(row.function)
            & paired["n_labels"].eq(int(row.best_n))
            & paired["rule_set"].eq(row.best_rule),
            "overhead_pct",
        ]
        expected_pairs = int(row.n_instances) * 31
        if len(selected) != expected_pairs:
            raise ValueError(
                f"Expected {expected_pairs} paired runtime observations for {row.function}; "
                f"found {len(selected)}"
            )
        overheads.append(float(selected.median()))

    result = per_function.copy()
    result["runtime_overhead_pct"] = overheads
    return result


def _fmt_p(p: float) -> str:
    if not np.isfinite(p):
        return "--"
    if p < 1e-3:
        return "$<10^{-3}$"
    return f"{p:.3f}"


def _fmt_gap(g: float) -> str:
    if g == 0:
        return "0"
    if g < 1e-3 or g >= 1e4:
        mant, exp = f"{g:.1e}".split("e")
        return f"${mant}\\!\\times\\!10^{{{int(exp)}}}$"
    return f"{g:.3f}"


def emit_body_table(df: pd.DataFrame, path: Path) -> None:
    lines = [
        "% Generado por code/11_generate_function_level_analysis.py. No editar a mano.",
        "\\startlandscape",
        "\\begin{table}[H]",
        "\\centering",
        "\\small",
        "\\caption{Function-level summary of the FCS configuration with the most per-instance rank wins, "
        "with ranks, wins, nominal significance, effect size, and runtime overhead summarized by function.}",
        "\\label{tab:function_level}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}l p{4cm} p{2.8cm} p{2.5cm} cccccc}",
        "\\toprule",
        "\\textbf{Function} & \\textbf{Landscape} & \\textbf{Dimensions} & \\textbf{Best FCS} & "
        "\\textbf{PSO rank} & \\textbf{FCS rank} & \\textbf{FCS wins} & \\textbf{Nominally significant wins} & "
        "\\boldmath$A_{12}$ & \\textbf{Overhead (\\%)} \\\\",
        "\\midrule",
    ]
    data_start = len(lines)
    previous = None
    class_display = {
        "Unimodal": "Unimodal",
        "Multimodal (scalable)": "Scalable multimodal",
        "Fixed-dimensional": "Fixed-dimensional",
    }
    for _, r in df.iterrows():
        if previous is not None and r["landscape_class"] != previous:
            lines.append("\\midrule")
        previous = r["landscape_class"]
        best = "--" if r["all_tied"] else f"\\texttt{{{r['best_fcs']}}}"
        lines.append(
            f"{r['function']} & {class_display[r['landscape_class']]} & "
            f"{r['dims']} & {best} & "
            f"{r['rank_pso_median']:.1f} & {r['rank_best_fcs_median']:.1f} & "
            f"{r['fcs_wins']}/{r['n_instances']} & {r['significant_wins']}/{r['n_instances']} & "
            f"{r['a12_median']:.2f} \\\\"
        )
    for row_record in df.itertuples(index=False):
        row_prefix = f"{row_record.function} & "
        row_index = next(
            (i for i, line in enumerate(lines[data_start:], start=data_start)
             if line.startswith(row_prefix)),
            None,
        )
        if row_index is None:
            raise ValueError(f"Could not locate generated table row for {row_record.function}")
        row_ending = r"\\"
        if not lines[row_index].endswith(row_ending):
            raise ValueError(f"Generated table row has no line ending: {row_record.function}")
        runtime_text = (
            "--" if not np.isfinite(row_record.runtime_overhead_pct)
            else f"{row_record.runtime_overhead_pct:.1f}"
        )
        lines[row_index] = (
            lines[row_index][:-len(row_ending)] + f" & {runtime_text} " + row_ending
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular*}",
        "\\noindent\\footnotesize",
        "Ranks are per-instance ranks among 33 configurations on median normalized gap (1 = best), "
        "summarized by the median over a function's dimensions. \\emph{FCS wins} counts instances "
        "where the selected FCS outranks PSO; the nominal significance count uses paired Wilcoxon $p<0.05$ "
        "on final fitness, without multiplicity correction. $A_{12}$ is the median Vargha--Delaney "
        "effect on final fitness ($A_{12}>0.5$ favours FCS). Median overhead is the median paired "
        "run-level overhead $100(t_{\\mathrm{FCS}}/t_{\\mathrm{PSO}}-1)$ pooled over dimensions; "
        "negative values indicate lower FCS runtime. Times are observed wall-clock values.",
        "\\par\\smallskip",
        "A dash in \\emph{Best FCS} marks functions for which all configurations tie at rank 1 on "
        "median normalized gap across the tested instances; it does not imply that every individual "
        "run reaches the reference optimum.",
        "\\end{table}",
        "\\finishlandscape",
        "",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[11] wrote {path.name}")


def emit_full_table(df: pd.DataFrame, path: Path, chunk: int = 22) -> None:
    lines = ["% Generado por code/11_generate_function_level_analysis.py. No editar a mano.",
             "% Tabla completa por instancia (material suplementario)."]
    blocks = [df.iloc[i:i + chunk] for i in range(0, len(df), chunk)]
    for k, block in enumerate(blocks, start=1):
        part = f" (part {k} of {len(blocks)})" if len(blocks) > 1 else ""
        lines += [
            "\\begin{table}[H]",
            "\\centering",
            "\\footnotesize",
            f"\\caption{{Per-instance FCS--PSO comparisons{part} across the 62 benchmark instances. "
            "Ranks use median normalized gap over 33 configurations; $p$ and $A_{12}$ are from paired "
            "Wilcoxon comparisons of final fitness ($A_{12}>0.5$ favours FCS).}",
            f"\\label{{tab:function_level_full_{k}}}",
            "\\setlength{\\tabcolsep}{3.5pt}",
            "\\begin{tabular}{llcccccccc}",
            "\\toprule",
            "\\textbf{Instance} & \\textbf{Best FCS} & \\boldmath$n$ & \\textbf{R} & "
            "\\textbf{PSO rk.} & \\textbf{FCS rk.} & \\textbf{PSO gap} & \\textbf{FCS gap} & "
            "\\boldmath$p$ & \\boldmath$A_{12}$ \\\\",
            "\\midrule",
        ]
        for _, r in block.iterrows():
            instance = r["instance"].replace("_", r"\_")
            lines.append(
                f"{instance} & \\texttt{{{r['best_fcs']}}} & {r['best_n']} & "
                f"{r['best_rule']} & {r['rank_pso']} & {r['rank_best_fcs']} & "
                f"{_fmt_gap(r['gap_pso'])} & {_fmt_gap(r['gap_best_fcs'])} & "
                f"{_fmt_p(r['p_value'])} & {r['a12']:.2f} \\\\"
            )
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[11] wrote {path.name} ({len(blocks)} parts)")


def emit_heatmap(rank: pd.DataFrame, per_instance: pd.DataFrame) -> None:
    wide = rank.pivot_table(index="instance", columns="mh_raw", values="rank")
    # Columns ordered by overall mean rank, rows grouped by subset then function then dim.
    wide = wide[wide.mean().sort_values().index]
    order = per_instance.sort_values(["subset", "function", "dim"],
                                     key=lambda s: s.map({f: i for i, f in enumerate(function_order(per_instance["function"]))})
                                     if s.name == "function" else s)["instance"]
    wide = wide.loc[order]

    fig, ax = plt.subplots(figsize=(7.0, 8.6))
    bounds = [1, 2, 4, 8, 12, 17, 22, 27, 33]
    cmap = plt.get_cmap("RdYlGn_r", len(bounds) - 1)
    im = ax.imshow(wide.values, aspect="auto", cmap=cmap,
                   norm=BoundaryNorm(bounds, cmap.N))

    ax.set_xticks(range(wide.shape[1]))
    ax.set_xticklabels([short_name(c) for c in wide.columns], rotation=90, fontsize=6)
    ax.set_yticks(range(wide.shape[0]))
    ax.set_yticklabels([i.replace("_D", " d=") for i in wide.index], fontsize=5.5)

    # Highlight the baseline column so the reader can locate PSO immediately.
    pso_col = list(wide.columns).index("PSO")
    ax.axvline(pso_col - 0.5, color="black", lw=1.1)
    ax.axvline(pso_col + 0.5, color="black", lw=1.1)
    ax.get_xticklabels()[pso_col].set_fontweight("bold")

    # Separator between the scalable (S1) and fixed-dimensional (S2) subsets.
    s2_start = int((per_instance.sort_values(["subset", "function", "dim"])["subset"] == "S1").sum())
    ax.axhline(s2_start - 0.5, color="black", lw=1.1)

    ax.set_xlabel("Configuration (ordered by mean rank)", fontsize=9)
    ax.set_ylabel("Instance", fontsize=9)

    cbar = fig.colorbar(im, ax=ax, orientation="horizontal", pad=0.06, fraction=0.035,
                        boundaries=bounds, ticks=bounds)
    cbar.set_label("Rank on the instance (1 = best of 33)", fontsize=8)
    cbar.ax.tick_params(labelsize=7)

    fig.tight_layout()
    for directory in (MS_FIGURES, OUT_FIG):
        directory.mkdir(parents=True, exist_ok=True)
        for ext in ("png", "pdf"):
            fig.savefig(directory / f"fig_function_heatmap.{ext}", dpi=300, bbox_inches="tight")
    plt.close(fig)
    print("[11] wrote fig_function_heatmap.{png,pdf}")


def main() -> int:
    for path in (RANKING, WILCOXON, META):
        if not path.exists():
            raise FileNotFoundError(f"missing input: {path}")

    rank = pd.read_csv(RANKING)
    wil = pd.read_csv(WILCOXON)

    per_instance = build_per_instance(rank, wil)
    per_function = add_runtime_overhead(build_per_function(per_instance))

    OUT_L3.mkdir(parents=True, exist_ok=True)
    MS_TABLES.mkdir(parents=True, exist_ok=True)
    for df, stem in ((per_instance, "function_level_per_instance"),
                     (per_function, "function_level_per_function")):
        df.to_csv(OUT_L3 / f"{stem}.csv", index=False)
        print(f"[11] wrote {stem}: {len(df):>3} rows")

    emit_body_table(per_function, MS_TABLES / "tab_function_level.tex")
    emit_full_table(per_instance, MS_TABLES / "tab_function_level_full.tex")
    emit_heatmap(rank, per_instance)

    wins = int((per_instance["winner_family"] == "PSO_FCS").sum())
    fcs_wins = per_instance[per_instance["winner_family"] == "PSO_FCS"]
    sig = int(((fcs_wins["p_value"] < ALPHA)).sum())
    distinct = fcs_wins["best_fcs"].nunique()
    print(f"[11] FCS outranks PSO on {wins}/{len(per_instance)} instances "
          f"({sig} significant at alpha={ALPHA}); "
          f"{distinct} distinct configurations win at least one instance.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
